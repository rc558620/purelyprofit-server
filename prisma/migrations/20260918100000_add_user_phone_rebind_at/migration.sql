-- AlterTable
ALTER TABLE "users"
  ADD COLUMN "phone_rebind_at" TIMESTAMP(3);

-- 说明：记录最近一次换绑手机号的时间，用于换绑频率限制（30 天冷静期）。
--
-- 背景：换绑只校验**新**手机号的短信验证码——用户换号后旧号已经收不到短信，
-- 要求校验旧号等于功能不可用。因此需要一道频率闸门：账号若被他人短暂拿到
-- （手机借人、微信仍处于登录态），对方可把手机号改成自己的，之后商家端
-- 所有触达（回访、营销短信）都会打到对方手机上。
-- 正常用户换号频率极低，30 天限制对真实场景无感。
--
-- 不回填历史数据：留空表示「从未换绑过」，首次换绑不受限制，
-- 与新增本列之前的行为一致。
